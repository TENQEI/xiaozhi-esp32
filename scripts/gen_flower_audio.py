#!/usr/bin/env python3
"""Validate Flower's independent manifest and generate embedded sound views."""
import argparse
import json
import re
import struct
from pathlib import Path

from prepare_flower_chimes import validate_ogg

GROUPS = ("clock", "greeting", "startup", "provisioning", "phrase_morning", "phrase_afternoon",
          "phrase_evening", "phrase_anytime", "session_start", "session_end")
REQUIRED_FILES = {f"clock_{i:02d}.ogg": "clock" for i in range(1, 13)} | {
    "greeting_morning.ogg": "greeting", "greeting_night.ogg": "greeting",
    "startup_ready.ogg": "startup", "wifi_config.ogg": "provisioning"}


def valid_recording_name(name, group):
    if not isinstance(name, str) or group not in GROUPS:
        return False
    if group in ("clock", "greeting", "startup", "provisioning"):
        return REQUIRED_FILES.get(name) == group
    match = re.fullmatch(rf"{group}_([0-9]{{2,}})\.ogg", name)
    return match is not None and int(match[1]) > 0


def load_manifest(path, validate_audio=True):
    path = Path(path)
    manifest = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(manifest, dict):
        raise ValueError("Flower manifest must be an object")
    if (manifest.get("version") != 1 or manifest.get("format") !=
            {"codec": "opus", "channels": 1, "sample_rate": 16000, "bitrate": 16000} or
            type(manifest.get("automatic_enabled")) is not bool):
        raise ValueError("unsupported Flower manifest version or audio format")
    records = manifest.get("audio")
    if not isinstance(records, list):
        raise ValueError("Flower recordings must be a list")
    seen = set()
    for item in records:
        if not isinstance(item, dict):
            raise ValueError("recording must be an object")
        name = item.get("file")
        if not valid_recording_name(name, item.get("category")) or name in seen:
            raise ValueError(f"unknown, duplicate or misclassified recording: {name}")
        if item.get("id") != Path(name).stem.upper() or not re.fullmatch(r"[A-Z0-9_]+", item["id"]):
            raise ValueError(f"invalid audio id: {name}")
        if any(type(item.get(key)) is not bool for key in ("enabled", "placeholder")):
            raise ValueError(f"enabled/placeholder must be boolean: {name}")
        duration = item.get("expected_duration_s")
        if isinstance(duration, bool) or not isinstance(duration, (int, float)) or not 0 < duration <= 60:
            raise ValueError(f"invalid expected duration: {name}")
        seen.add(name)
        if validate_audio:
            data = (path.parent / name).read_bytes()
            validate_ogg(data)
            head = data.find(b"OpusHead")
            if head < 0 or struct.unpack_from("<I", data, head + 12)[0] != 16000:
                raise ValueError(f"Opus input sample rate must be 16000 Hz: {name}")
    if not set(REQUIRED_FILES).issubset(seen):
        raise ValueError("all clock, greeting, startup and Wi-Fi configuration slots are required")
    # Match RandomPhraseIndex/PhraseCount's existing runtime bounds.
    enabled = [item for item in records if item["enabled"]]
    if sum(item["category"].startswith("phrase_") for item in enabled) > 64:
        raise ValueError("enabled phrases exceed the runtime limit of 64")
    for group in ("session_start", "session_end"):
        if sum(item["category"] == group for item in enabled) > 64:
            raise ValueError(f"enabled {group} clips exceed the runtime limit of 64")
    if validate_audio and {p.name for p in path.parent.glob("*.ogg")} != seen:
        raise ValueError("Flower directory and manifest file lists must match exactly")
    return manifest


def generate(manifest_path, output):
    manifest = load_manifest(manifest_path)
    lines = ["// Generated by gen_flower_audio.py; edit the manifest instead.", "#pragma once",
             "#include <array>", "#include <string_view>", "namespace Flower::Sounds {",
             "struct Clip { std::string_view data; int id; };"]
    records = sorted(manifest["audio"], key=lambda item: item["file"])
    for index, item in enumerate(records):
        stem, symbol = Path(item["file"]).stem, item["id"]
        lines += [f'extern const char {stem}_start[] asm("_binary_{stem}_ogg_start");',
                  f'extern const char {stem}_end[] asm("_binary_{stem}_ogg_end");',
                  f"inline const std::string_view {symbol}{{{stem}_start, static_cast<size_t>({stem}_end - {stem}_start)}};",
                  f"inline constexpr bool {symbol}_ENABLED = {'true' if item['enabled'] else 'false'};"]
    for group in GROUPS:
        selected = [(i, item) for i, item in enumerate(records) if item["category"] == group
                    and (item["enabled"] or group == "clock")]
        # Clock slots must never shift when an individual hour is disabled.
        values = ",".join("{" + (item["id"] if item["enabled"] else "std::string_view{}") +
                           f",{i}" + "}" for i, item in selected)
        lines.append(f"inline const std::array<Clip,{len(selected)}> {group.upper()}{{{{{values}}}}};")
    lines += [f"inline constexpr bool AUTOMATIC_ENABLED = {'true' if manifest['automatic_enabled'] else 'false'};", "}", ""]
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(lines)
    if not output.exists() or output.read_text() != text:
        output.write_text(text, encoding="utf-8")
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        manifest = generate(args.manifest, args.output)
    except (ValueError, OSError, KeyError, TypeError) as error:
        parser.exit(1, f"Flower audio: {error}\n")
    size = sum((args.manifest.parent / item["file"]).stat().st_size for item in manifest["audio"])
    print(f"Flower audio: {len(manifest['audio'])} files, {size} bytes, {sum(item['placeholder'] for item in manifest['audio'])} placeholders")


if __name__ == "__main__":
    main()
